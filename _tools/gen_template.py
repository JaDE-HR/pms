HEAD_FILL = PatternFill('solid', fgColor='1D1D1F')
HEAD_FONT = Font(color='FFFFFF', bold=True, size=10)
WEEK_FILL = PatternFill('solid', fgColor='6B6B70')
NOTE_FONT = Font(color='7A7A7A', size=10)
TITLE_FONT = Font(bold=True, size=13)
THIN = Border(*[Side('thin', color='D9D9D9')] * 4)

wb = Workbook()


def sheet(name, headers, rows, widths=None, note=None, freeze='A2'):
    ws = wb.create_sheet(name)
    ws.append(headers)
    for c in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=c)
        cell.fill = HEAD_FILL if not str(headers[c - 1]).endswith('주') else WEEK_FILL
        cell.font = HEAD_FONT
        cell.alignment = Alignment(horizontal='center', vertical='center')
        cell.border = THIN
    for r in rows:
        ws.append(r)
    for i, w in enumerate(widths or [], start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = freeze
    ws.row_dimensions[1].height = 22
    if note:
        ws.cell(row=len(rows) + 3, column=1, value=note).font = NOTE_FONT
    return ws


